"""Nix development shell provenance and environment tests (PRD 16.2, 22.14).

Validates that:
1. Tools resolve to Nix store paths (not .venv, pip, or system paths).
2. The grossy executable is store-backed with correct module paths.
3. No ambient Python environment (PYTHONHOME, VIRTUAL_ENV, user-site) leaks.
4. Package resources (SQL migrations, seed fixtures) are included in the
   installed package.
5. Source tests can import grossy from the repository src/ directory.

These required tests fail outside the project Nix development shell.
"""

from __future__ import annotations

