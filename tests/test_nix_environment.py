def _is_nix_shell() -> bool:
    """Detect if we're running inside a Nix development shell."""
    expected = os.environ.get("GROSSY_SHELL_PYTHON", "")
    return (
        os.environ.get("GROSSY_SHELL_PROJECT") == "grossy-python312-v1"
        and expected.startswith("/nix/store/")
        and shutil.which("python3") == f"{expected}/bin/python3"
    )


def _is_store_path(path: str) -> bool:
    """Check if a path is in the Nix store."""
    return path.startswith("/nix/store/")


def _require_nix_shell() -> None:
    """Fail (not skip) when the test is not running in the Nix development shell.

    The provenance guard in Justfile setup must be tested even when it fails.
    Silent skips would mask the very condition we are testing for.
    """
    assert _is_nix_shell(), (
        "These tests require the Nix development shell. "
        "Run via: nix develop --no-write-lock-file -c python3 -m pytest"
    )


